namespace Rdmp.Core.Tests.Reports;

/// <summary>
/// Read-back helpers for asserting on the content of .docx files generated by the report classes
/// </summary>
internal sealed class DocXContents
{
    /// <summary>
    /// Text of each top level body paragraph (excluding those inside tables)
    /// </summary>
    public List<string> Paragraphs { get; }

    /// <summary>
    /// Each table as rows of cell texts
    /// </summary>
    public List<string[][]> Tables { get; }

    /// <summary>
    /// The file data of each image embedded in the document
    /// </summary>
    public List<byte[]> Images { get; }

    public int ImageCount => Images.Count;

    /// <summary>
    /// Number of inline drawings referencing an embedded image
    /// </summary>
    public int DrawingCount { get; }

    public List<string> FooterTexts { get; }

    public PageSize PageSize { get; }

    public PageMargin PageMargin { get; }

    public int PageBreakCount { get; }

    /// <summary>
    /// The distinct font sizes (in points, null where none is set) of the runs with each text
    /// </summary>
    private readonly Dictionary<string, HashSet<int?>> _fontSizes = new();

    public List<ValidationErrorInfo> ValidationErrors { get; }

    private DocXContents(WordprocessingDocument doc)
    {
        var main = doc.MainDocumentPart ?? throw new AssertionException("Document has no main part");
        var body = main.Document.Body ?? throw new AssertionException("Document has no body");

        Paragraphs = body.Elements<Paragraph>().Select(p => p.InnerText).ToList();
        Tables = body.Elements<Table>().Select(t => t.Elements<TableRow>()
            .Select(r => r.Elements<TableCell>().Select(c => c.InnerText).ToArray()).ToArray()).ToList();
        Images = main.ImageParts.Select(static part =>
        {
            using var stream = part.GetStream(FileMode.Open, FileAccess.Read);
            using var copy = new MemoryStream();
            stream.CopyTo(copy);
            return copy.ToArray();
        }).ToList();
        DrawingCount = body.Descendants<DocumentFormat.OpenXml.Drawing.Blip>().Count();
        FooterTexts = main.FooterParts.Select(f => f.Footer.InnerText).ToList();

        var sectPr = body.Elements<SectionProperties>().Last();
        PageSize = sectPr.GetFirstChild<PageSize>();
        PageMargin = sectPr.GetFirstChild<PageMargin>();
        PageBreakCount = body.Descendants<Break>().Count(b => b.Type?.Value == BreakValues.Page);

        foreach (var run in body.Descendants<Run>())
        {
            var size = run.RunProperties?.FontSize?.Val?.Value;

            if (!_fontSizes.TryGetValue(run.InnerText, out var sizes))
                _fontSizes.Add(run.InnerText, sizes = new HashSet<int?>());

            sizes.Add(size == null ? null : int.Parse(size) / 2);
        }

        ValidationErrors = new OpenXmlValidator().Validate(doc).ToList();
    }

    public static DocXContents Read(string path)
    {
        Assert.That(File.Exists(path), $"Expected document {path} to exist");
        using var doc = WordprocessingDocument.Open(path, false);
        return new DocXContents(doc);
    }

    /// <summary>
    /// Returns the font size (in points) of the runs whose text is exactly <paramref name="runText"/>, or null if they
    /// do not set one.  Fails if there is no such run or if the runs disagree, so a size is never asserted against
    /// only some of the runs with that text.
    /// </summary>
    public int? FontSizeOf(string runText)
    {
        if (!_fontSizes.TryGetValue(runText, out var sizes))
            throw new AssertionException($"Document has no run with the text '{runText}'");

        if (sizes.Count > 1)
            throw new AssertionException(
                $"Runs with the text '{runText}' have conflicting font sizes: {string.Join(", ", sizes.OrderBy(s => s).Select(s => s?.ToString() ?? "none"))}");

        return sizes.Single();
    }

    public void AssertValid() =>
        Assert.That(ValidationErrors.Select(e => $"{e.Path?.XPath}: {e.Description}"), Is.Empty,
            "Generated document failed OpenXml schema validation");
}

/// <summary>
/// Builds PNG images for tests without needing an imaging library
/// </summary>
internal static class TestPng
{
    /// <summary>
    /// Returns the file data of a valid PNG image of the given size in pixels, filled with a single colour
    /// </summary>
    public static byte[] Create(int width, int height, byte red = 255, byte green = 0, byte blue = 0)
    {
        using var png = new MemoryStream();
        png.Write([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]);

        var header = new byte[13];
        BinaryPrimitives.WriteInt32BigEndian(header, width);
        BinaryPrimitives.WriteInt32BigEndian(header.AsSpan(4), height);
        header[8] = 8; // bits per channel
        header[9] = 2; // red, green and blue channels
        WriteChunk(png, "IHDR", header);

        // each row is a filter type (0 for none) followed by its pixels
        var row = new byte[1 + width * 3];
        for (var x = 0; x < width; x++)
        {
            row[1 + x * 3] = red;
            row[2 + x * 3] = green;
            row[3 + x * 3] = blue;
        }

        using var pixels = new MemoryStream();
        using (var zlib = new ZLibStream(pixels, CompressionLevel.Optimal, true))
        {
            for (var y = 0; y < height; y++)
                zlib.Write(row);
        }

        WriteChunk(png, "IDAT", pixels.ToArray());
        WriteChunk(png, "IEND", []);

        return png.ToArray();
    }

    /// <summary>
    /// A chunk is its data length, its type and data, then a checksum of the type and data
    /// </summary>
    private static void WriteChunk(Stream png, string type, byte[] data)
    {
        Span<byte> number = stackalloc byte[4];
        byte[] typeAndData = [.. Encoding.ASCII.GetBytes(type), .. data];

        BinaryPrimitives.WriteInt32BigEndian(number, data.Length);
        png.Write(number);
        png.Write(typeAndData);
        BinaryPrimitives.WriteUInt32BigEndian(number, Crc32(typeAndData));
        png.Write(number);
    }

    private static uint Crc32(ReadOnlySpan<byte> data)
    {
        var crc = 0xFFFFFFFFu;

        foreach (var b in data)
        {
            crc ^= b;
            for (var bit = 0; bit < 8; bit++)
                crc = (crc & 1) != 0 ? (crc >> 1) ^ 0xEDB88320u : crc >> 1;
        }

        return ~crc;
    }
}
